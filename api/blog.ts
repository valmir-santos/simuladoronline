const KV_BLOG_KEY = 'simulador:blog';
const KV_TWEETED_KEY = 'simulador:blog:tweeted';

function getRedis(): Redis | null {
  const url = process.env.KV_REST_API_URL || process.env.UPSTASH_REDIS_REST_URL;
  const token = process.env.KV_REST_API_TOKEN || process.env.UPSTASH_REDIS_REST_TOKEN;
  if (!url || !token) return null;
  return new Redis({ url, token });
}

async function loadBlogPosts(): Promise<BlogPostItem[]> {
  const redis = getRedis();
  if (redis) {
    try {
      const stored = await redis.get<BlogPostItem[]>(KV_BLOG_KEY);
      if (stored && Array.isArray(stored) && stored.length > 0) return stored;
      await redis.set(KV_BLOG_KEY, SEED_BLOG_POSTS);
      return SEED_BLOG_POSTS;
    } catch (e) {
      console.warn('Redis indisponível para o blog, usando dados de fallback:', e);
    }
  }
  return SEED_BLOG_POSTS;
}

async function saveBlogPosts(posts: BlogPostItem[]): Promise<void> {
  const redis = getRedis();
  if (redis) {
    try {
      await redis.set(KV_BLOG_KEY, posts);
    } catch (e) {
      console.warn('Erro ao gravar blog posts no Redis:', e);
    }
  }
}

export default async function handler(req: VercelRequest, res: VercelResponse) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'GET, POST, PUT, DELETE, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type');

  if (req.method === 'OPTIONS') {
    return res.status(200).end();
  }

  const posts = await loadBlogPosts();
  const now = new Date();

  // GET: Listar todos os posts do blog
  if (req.method === 'GET') {
    const isAll = req.query?.all === 'true';
    if (isAll) {
      // Painel administrativo recebe todos os posts, incluindo futuros agendamentos
      return res.status(200).json(posts);
    }
    // O público geral só vê posts cuja data/hora já passou
    const published = posts.filter(post => new Date(post.date) <= now);
    return res.status(200).json(published);
  }

  const body = req.body || {};
  const masterPin = '(}-!#$%*V@1miR$632!.';

  // PUT: Editar um post existente
  if (req.method === 'PUT') {
    const { id, title, excerpt, content, category, imageUrl, sourceUrl, date, pin } = body;

    if (pin !== masterPin && pin !== '2026' && pin !== 'simulador') {
      return res.status(401).json({ error: 'Senha de acesso incorreta' });
    }

    const postIndex = posts.findIndex(p => p.id === String(id) || p.slug === String(id));
    if (postIndex === -1) {
      return res.status(404).json({ error: 'Artigo não encontrado para edição' });
    }

    posts[postIndex] = {
      ...posts[postIndex],
      title: title ? title.trim() : posts[postIndex].title,
      excerpt: excerpt ? excerpt.trim() : posts[postIndex].excerpt,
      content: content || posts[postIndex].content,
      category: category || posts[postIndex].category,
      imageUrl: imageUrl || posts[postIndex].imageUrl,
      sourceUrl: sourceUrl || posts[postIndex].sourceUrl,
      date: date || posts[postIndex].date
    };

    await saveBlogPosts(posts);

    return res.status(200).json({
      success: true,
      post: posts[postIndex]
    });
  }

  // POST: Adicionar um novo post (Robô IA ou Manual)
  if (req.method === 'POST') {
    const { title, excerpt, content, category, imageUrl, sourceUrl, date, pin } = body;

    if (!title || !content) {
      return res.status(400).json({ error: 'Título e conteúdo são obrigatórios' });
    }

    const slug = title
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/(^-|-$)/g, '');

    const newPost: BlogPostItem = {
      id: `${Date.now()}-${slug.substring(0, 30)}`,
      slug,
      title: title.trim(),
      excerpt: excerpt || title.substring(0, 150),
      content,
      category: category || 'Mercado',
      author: pin === masterPin || pin === '2026' || pin === 'simulador' ? 'Redação Simulador On-Line' : 'IA Simulador On-Line',
      date: date || new Date().toISOString(),
      readTime: '4 min de leitura',
      imageUrl: imageUrl || 'https://images.unsplash.com/photo-1505751172876-fa1923c5c528?auto=format&fit=crop&q=80&w=1200',
      sourceUrl: sourceUrl || 'https://www.ans.gov.br',
      autoGenerated: true
    };

    posts.unshift(newPost);
    await saveBlogPosts(posts);

    return res.status(201).json({
      success: true,
      post: newPost
    });
  }

  // DELETE: Remover um post do blog
  if (req.method === 'DELETE') {
    const { id, pin } = body || req.query || {};

    if (pin !== masterPin && pin !== '2026' && pin !== 'simulador') {
      return res.status(401).json({ error: 'Senha incorreta' });
    }

    if (!id) {
      return res.status(400).json({ error: 'ID do post é obrigatório' });
    }

    const filtered = posts.filter(p => p.id !== String(id) && p.slug !== String(id));

    if (posts.length === filtered.length) {
      return res.status(404).json({ error: 'Artigo não encontrado no catálogo' });
    }

    await saveBlogPosts(filtered);

    return res.status(200).json({
      success: true,
      message: 'Artigo removido com sucesso do blog central'
    });
  }

  return res.status(405).json({ error: 'Método não permitido' });
}
